function getInitialLanguage(): 'en' | 'fr' {
  try {
    return localStorage.getItem('pride-map-language') === 'fr' ? 'fr' : 'en';
  } catch (error) {
    console.warn('Could not read saved language preference:', error);
    return 'en';
  }
}

void i18n.use(initReactI18next).init({
  resources: translations,
  lng: getInitialLanguage(),
  fallbackLng: 'en',
  supportedLngs: ['en', 'fr'],
  interpolation: { escapeValue: false },
  initAsync: false,
});

i18n.on('languageChanged', (language) => {
  const normalizedLanguage = language.startsWith('fr') ? 'fr' : 'en';
  document.documentElement.lang = normalizedLanguage;
  try {
    localStorage.setItem('pride-map-language', normalizedLanguage);
  } catch (error) {
    console.warn('Could not save language preference:', error);
  }
});

document.documentElement.lang = i18n.language.startsWith('fr') ? 'fr' : 'en';

export default i18n;
